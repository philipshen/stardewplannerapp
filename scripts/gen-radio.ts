/**
 * Builds the radio station list (src/audio/stations.generated.ts).
 *
 * Built-in stations use the soundtrack assignments in scripts/data/soundtrack.json.
 * To add a station, make a folder in assets/music/stations/ and put audio files in it:
 *   assets/music/stations/<Station Name>/<Track Title>.(m4a|mp3|ogg|wav)
 * The folder name is the station name and each file name is a track title. Use only music that you may ship.
 *
 * Run: npx tsx scripts/gen-radio.ts   (also part of `npm run gen`)
 */
import fs from 'node:fs';
import path from 'node:path';
import soundtrack from './data/soundtrack.json';

const ROOT = path.join(__dirname, '..');
const MUSIC = path.join(ROOT, 'assets', 'music');
type Track = { title: string; file: string; season?: string };
type Station = { id: string; name: string; color: string; tracks: Track[] };

/** Each soundtrack track belongs to one activity; season radio draws across them. */
const ACTIVITY_STATIONS = [
  { id: 'farming', name: 'Farming Radio', color: '#5ab83a' },
  { id: 'foraging', name: 'Foraging Radio', color: '#3ab89a' },
  { id: 'fighting', name: 'Fighting Radio', color: '#c83a3a' },
  { id: 'fishing', name: 'Fishing Radio', color: '#3a72c8' },
  { id: 'mining', name: 'Mining Radio', color: '#8a5ad6' },
];
const COLORS = ['#5ab83a', '#3a72c8', '#c84a8a', '#3ab89a', '#c83a3a', '#8a5ad6', '#e0782a'];
for (const track of soundtrack) {
  if (!ACTIVITY_STATIONS.some((s) => s.id === track.station)) throw new Error(`Unknown station for ${track.title}`);
  if (!fs.existsSync(path.join(MUSIC, track.file))) throw new Error(`Missing soundtrack file: ${track.file}`);
}
const stations: Station[] = ACTIVITY_STATIONS.map((s) => ({ ...s, tracks: soundtrack.filter((t) => t.station === s.id) }));
const extra = path.join(MUSIC, 'stations');
if (fs.existsSync(extra)) {
  fs.readdirSync(extra, { withFileTypes: true }).filter((d) => d.isDirectory()).sort((a, b) => a.name.localeCompare(b.name)).forEach((d, i) => {
    const tracks = fs.readdirSync(path.join(extra, d.name)).filter((f) => /\.(m4a|mp3|ogg|wav|aac)$/i.test(f)).sort()
      .map((f) => ({ title: f.replace(/\.[a-z0-9]+$/i, '').replace(/^\d+[\s._-]+/, ''), file: `stations/${d.name}/${f}` }));
    if (tracks.length) stations.push({ id: 'x-' + d.name.toLowerCase().replace(/[^a-z0-9]+/g, '-'), name: d.name, color: COLORS[i % COLORS.length], tracks });
  });
}

const q = (s: string) => JSON.stringify(s);
const lines = [
  '// AUTO-GENERATED by scripts/gen-radio.ts — do not edit.',
  "export type RadioTrack = { title: string; source: number; season?: 'spring' | 'summer' | 'fall' | 'winter' };",
  'export type RadioStation = { id: string; name: string; color: string; tracks: RadioTrack[] };',
  'export const RADIO_STATIONS: RadioStation[] = [',
  ...stations.map((s) => `  { id: ${q(s.id)}, name: ${q(s.name)}, color: ${q(s.color)}, tracks: [\n${s.tracks.map((t) => `    { title: ${q(t.title)}, source: require(${q('../../assets/music/' + t.file)})${t.season ? `, season: ${q(t.season)}` : ''} },`).join('\n')}\n  ] },`),
  '];',
  '',
];
fs.writeFileSync(path.join(ROOT, 'src', 'audio', 'stations.generated.ts'), lines.join('\n'));
console.log(stations.map((s) => `${s.name}: ${s.tracks.length} tracks`).join('\n'));
