/** Render every shipped sample and generate Metro's static image references. */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import templates from '../src/data/generated/templates.json';
const root = path.join(__dirname, '..');
fs.mkdirSync(path.join(root, 'assets/gen/samples'), { recursive: true });
const images = templates.map((t, i) => {
  const slug = t.name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  execFileSync(process.execPath, ['--import', 'tsx', 'scripts/preview-scene.ts', '--template', String(i), '--scale', t.map === 'big-shed' ? '1' : '0.5', '--out', `assets/gen/samples/${slug}.png`], { cwd: root, stdio: 'inherit' });
  return `  require('../../../assets/gen/samples/${slug}.png'),`;
});
fs.writeFileSync(path.join(root, 'src/data/generated/templateImages.ts'), `// Generated by scripts/render-samples.ts\nexport const TEMPLATE_IMAGES = [\n${images.join('\n')}\n];\n`);
